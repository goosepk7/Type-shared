#!/usr/bin/env python3
"""Upload assets/textures/*.png to Roblox as Image assets (Open Cloud Assets API) and record ids.

    python3 assets/textures/upload.py --group 685727405     # uploads new/changed files only

Auth: an Open Cloud API key with asset:write in $ROBLOX_API_KEY (sent as x-api-key), or an environment whose
HTTPS proxy injects credentials. Results go to assets/textures/ids.json ({name: {id, sha1}}); then run
`python3 assets/textures/upload.py --write-luau` (done automatically after an upload) to refresh the id table
in src/Shared/Effects/AssetIds.luau. assetType "Image" returns an id usable directly as rbxassetid:// in
ParticleEmitter.Texture / Beam.Texture / Decal.Texture (a "Decal" upload would return a decal id instead).
"""
import hashlib, json, os, subprocess, sys, time

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
IDS = os.path.join(HERE, "ids.json")
LUAU = os.path.join(ROOT, "src", "Shared", "Effects", "AssetIds.luau")
API = "https://apis.roblox.com/assets/v1"


def curl(args):
    key = os.environ.get("ROBLOX_API_KEY")
    hdr = ["-H", "x-api-key: " + key] if key else []
    out = subprocess.run(["curl", "-sS", "-m", "90"] + hdr + args, capture_output=True, text=True, check=True).stdout
    return json.loads(out)


def upload(path, name, group):
    req = json.dumps({"assetType": "Image", "displayName": "WE_FX_" + name, "description": "WordEngine VFX texture " + name,
                      "creationContext": {"creator": {"groupId": str(group)}}})
    op = curl(["-X", "POST", API + "/assets", "-F", "request=" + req + ";type=application/json",
               "-F", "fileContent=@" + path + ";type=image/png"])
    opid = op.get("operationId")
    if not opid:
        raise RuntimeError("upload failed: %r" % op)
    for _ in range(30):
        time.sleep(2)
        st = curl([API + "/operations/" + opid])
        if st.get("done"):
            resp = st.get("response") or {}
            if "assetId" not in resp:
                raise RuntimeError("operation finished without asset: %r" % st)
            return resp["assetId"], (resp.get("moderationResult") or {}).get("moderationState", "?")
    raise RuntimeError("timed out waiting for " + opid)


def write_luau(ids):
    lines = ["--!strict", "-- GENERATED by assets/textures/upload.py from assets/textures/ids.json. Do not edit by hand.",
             "-- Roblox Image asset ids for the procedural VFX textures. Missing names fall back (see Assets.luau).", "return {"]
    for name in sorted(ids):
        lines.append('\t%s = "rbxassetid://%s",' % (name, ids[name]["id"]))
    lines.append("}")
    open(LUAU, "w").write("\n".join(lines) + "\n")
    print("wrote", os.path.relpath(LUAU, ROOT))


def main():
    ids = json.load(open(IDS)) if os.path.exists(IDS) else {}
    if "--write-luau" in sys.argv:
        write_luau(ids)
        return
    group = sys.argv[sys.argv.index("--group") + 1] if "--group" in sys.argv else None
    if not group:
        sys.exit("--group <groupId> required")
    changed = False
    for f in sorted(os.listdir(HERE)):
        if not f.endswith(".png"):
            continue
        name = f[:-4]
        sha = hashlib.sha1(open(os.path.join(HERE, f), "rb").read()).hexdigest()
        if ids.get(name, {}).get("sha1") == sha:
            continue
        asset, mod = upload(os.path.join(HERE, f), name, group)
        ids[name] = {"id": asset, "sha1": sha, "moderation": mod}
        changed = True
        print(name, asset, mod)
        json.dump(ids, open(IDS, "w"), indent=1, sort_keys=True)
    if changed or not os.path.exists(LUAU):
        write_luau(ids)


if __name__ == "__main__":
    main()
