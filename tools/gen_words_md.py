#!/usr/bin/env python3
"""Generate WORDS.md: library stats, coverage by category/element/size/shape, signature list sample."""
import json, glob, collections, os, sys
sys.path.insert(0, os.path.dirname(__file__))
from schema import ELEMENT, CATEGORY, SIZE, SHAPE

E = []
for f in sorted(glob.glob("data/words/*.jsonl")):
    for l in open(f, encoding="utf-8"):
        if l.strip():
            e = json.loads(l); e["_file"] = os.path.basename(f).split("_")[0]; E.append(e)
mats = json.load(open("data/materials.json"))
mods = json.load(open("data/modifiers.json"))
modlist = mods["modifiers"] if isinstance(mods, dict) else mods
mis = sum(1 for l in open("data/misspellings.jsonl") if l.strip())
aliases = sum(len(e.get("a", [])) for e in E)
ms = sum(len(e.get("ms", [])) for e in E)
sig = [e for e in E if e.get("sig")]
danger = [e for e in E if "danger" in e.get("t", [])]

def table(title, key, order):
    c = collections.Counter(e[key] for e in E)
    rows = [f"| {k} | {c.get(k,0):,} | {100*c.get(k,0)/len(E):.1f}% |" for k in order]
    return f"### {title}\n\n| {title} | Entries | Share |\n|---|---:|---:|\n" + "\n".join(rows) + "\n"

out = [f"""# WORDS.md: word library stats

Generated by `python3 tools/gen_words_md.py` from `data/`. Do not edit by hand.

| Metric | Count |
|---|---:|
| Canonical entries | {len(E):,} |
| Aliases (plurals, synonyms, regional, slang) | {aliases:,} |
| Per-entry misspellings | {ms:,} |
| Misspelling table rows | {mis:,} |
| Signature entries | {len(sig):,} |
| Danger-tagged entries (power 9-10) | {len(danger):,} |
| Modifiers | {len(modlist):,} |
| Materials | {len(mats):,} |

## Coverage
"""]
dom = collections.Counter(e["_file"] for e in E)
out.append("### By authoring domain\n\n| Domain | Entries |\n|---|---:|\n" + "\n".join(f"| {k} | {v:,} |" for k, v in dom.most_common()) + "\n")
out.append(table("Category", "c", CATEGORY))
out.append(table("Element", "e", ELEMENT))
out.append(table("Size", "z", SIZE))
out.append(table("Shape", "s", SHAPE))
pw = collections.Counter(e["p"] for e in E)
out.append("### Power distribution\n\n| Power | Entries |\n|---:|---:|\n" + "\n".join(f"| {p} | {pw.get(p,0):,} |" for p in range(1, 11)) + "\n")
fam = collections.Counter(m["family"] for m in mats)
out.append("### Materials by family\n\n| Family | Materials |\n|---|---:|\n" + "\n".join(f"| {k} | {v} |" for k, v in fam.most_common()) + "\n")
kinds = collections.Counter(m["kind"] for m in modlist)
out.append("### Modifiers by kind\n\n| Kind | Modifiers |\n|---|---:|\n" + "\n".join(f"| {k} | {v} |" for k, v in kinds.most_common()) + "\n")
out.append("## Signature words (first 120 alphabetically)\n\n" + ", ".join(sorted(e["w"] for e in sig)[:120]) + "\n")
open("WORDS.md", "w", encoding="utf-8").write("\n".join(out))
print("WORDS.md:", len(E), "entries")
