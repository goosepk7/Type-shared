#!/usr/bin/env python3
"""Write the always-loaded hero index src/Shared/Summon/Heroes/Index.luau from the generated family modules
src/Shared/Summon/Heroes/Data/<family>.luau (pure Python, no mesher dependencies).

  python3 tools/meshgen/heroes/index.py           rewrite Index.luau
  python3 tools/meshgen/heroes/index.py --check   exit 1 if Index.luau is stale

build.py calls this after writing data (write_index), so a new family is registered by building it. The index maps
every hero id to its family plus the cheap metadata callers read without the sculpt data (plan, gait, tags):
Summon/Heroes/init.luau requires a family module only when one of its heroes is first built (tests/specs
hero_index.spec.luau fails when this file is stale).
"""
import json, os, re, sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(os.path.dirname(HERE)))
HEROES = os.path.join(ROOT, "src/Shared/Summon/Heroes")
DATA = os.path.join(HEROES, "Data")
INDEX = os.path.join(HEROES, "Index.luau")

STR = r'"(?:[^"\\]|\\.)*"'
TOP = re.compile(r'^\t\[(' + STR + r')\] = \{$')
PLAN = re.compile(r'^\t\tplan = (' + STR + r'), gait = (' + STR + r'),$')
TAGS = re.compile(r'^\t\ttags = \{ (.*) \},$')


def parse(path):
    """[(id, plan, gait, tags)] of one generated family module (format: build.py hero_lua)."""
    out = []
    lines = open(path, encoding="utf-8").read().split("\n")
    for i, line in enumerate(lines):
        m = TOP.match(line)
        if not m:
            continue
        hid = json.loads(m.group(1))
        pm = PLAN.match(lines[i + 1]) if i + 1 < len(lines) else None
        if not pm:
            raise SystemExit(f"{path}:{i + 2}: hero {hid!r} has no 'plan = ..., gait = ...,' line")
        tags = []
        tm = TAGS.match(lines[i + 2]) if i + 2 < len(lines) else None
        if tm:
            tags = [json.loads(s) for s in re.findall(STR, tm.group(1))]
        out.append((hid, json.loads(pm.group(1)), json.loads(pm.group(2)), tags))
    return out


def render():
    fams = sorted(f[:-5] for f in os.listdir(DATA) if f.endswith(".luau"))
    owner = {}
    rows = []
    for fam in fams:
        for hid, plan, gait, tags in parse(os.path.join(DATA, fam + ".luau")):
            key = hid.lower()
            if key in owner:
                raise SystemExit(f"hero {hid!r} is in two families: {owner[key]} and {fam}")
            owner[key] = fam
            rows.append((key, fam, plan, gait, tags))
    rows.sort()
    q = json.dumps
    L = ["--!strict",
         "-- GENERATED by tools/meshgen/heroes/index.py (run by build.py) from Data/*.luau. Do not edit.",
         "-- Always loaded: hero id -> family module + the metadata callers read without the sculpt data.",
         "-- Summon/Heroes/init.luau requires Data/<family> only when one of its heroes is first needed.",
         "return {",
         "\tfamilies = { " + ", ".join(q(f) for f in fams) + " },",
         "\theroes = {"]
    for key, fam, plan, gait, tags in rows:
        t = (", tags = { " + ", ".join(q(x) for x in tags) + " }") if tags else ""
        L.append(f"\t\t[{q(key)}] = {{ f = {q(fam)}, plan = {q(plan)}, gait = {q(gait)}{t} }},")
    L.append("\t},")
    L.append("}")
    return "\n".join(L) + "\n", len(rows), len(fams)


def write():
    text, n, f = render()
    with open(INDEX, "w", encoding="utf-8") as fh:
        fh.write(text)
    return n, f


def main():
    text, n, f = render()
    if "--check" in sys.argv:
        cur = open(INDEX, encoding="utf-8").read() if os.path.exists(INDEX) else ""
        if cur != text:
            print("Index.luau is stale: run python3 tools/meshgen/heroes/index.py")
            sys.exit(1)
        print(f"Index.luau up to date ({n} heroes, {f} families)")
        return
    write()
    print(f"wrote {INDEX} ({n} heroes, {f} families)")


if __name__ == "__main__":
    main()
