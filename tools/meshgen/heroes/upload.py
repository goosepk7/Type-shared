#!/usr/bin/env python3
"""Upload hero models as ONE Model asset each (a multi-node .glb: one MeshPart per piece, named by its piece id) and
write src/Shared/Summon/Heroes/Packs.luau ({ [heroId] = assetId }) + data/hero_packs.json (hash cache).

  python3 tools/meshgen/heroes/upload.py [--only lion,tiger] [--dry] [--force] [--sync]

Verified on a live server: InsertService:LoadAsset(pack) returns Model > Model(<name>) > Model(<piece>_Node) >
MeshPart(<piece>) with the native sizes intact. The runtime loads a pack the first time its hero is summoned
(Summon.ensureMeshes on the server) and registers every MeshPart with MeshLibrary.
"""
import argparse, hashlib, json, os, subprocess, sys, time

HERE = os.path.dirname(os.path.abspath(__file__))
MG = os.path.dirname(HERE)
ROOT = os.path.dirname(os.path.dirname(MG))
sys.path.insert(0, MG)
sys.path.insert(0, HERE)
OUT = os.path.join(MG, "out")
PACKS = os.path.join(ROOT, "data/hero_packs.json")
LUAU = os.path.join(ROOT, "src/Shared/Summon/Heroes/Packs.luau")
LOG = os.path.join(MG, "uploads.log")

import trimesh  # noqa: E402

import importlib.util  # noqa: E402

_spec = importlib.util.spec_from_file_location("mg_upload", os.path.join(MG, "upload.py"))
base = importlib.util.module_from_spec(_spec)  # tools/meshgen/upload.py: upload(), poll()
_spec.loader.exec_module(base)
import build  # noqa: E402
import kit  # noqa: E402


def pack(hid):
    H = build.get(hid)
    keys = []
    for p in H.parts:
        if p["kind"] == "piece" and p["key"] not in keys:
            keys.append(p["key"])
    sc = trimesh.Scene()
    hsh = hashlib.sha1()
    for k in keys:
        path = os.path.join(OUT, k + ".glb")
        data = open(path, "rb").read()
        hsh.update(k.encode())
        hsh.update(data)
        s = trimesh.load(path, force="scene", process=False)
        m = list(s.geometry.values())[0]
        sc.add_geometry(m, node_name=k, geom_name=k)
    out = os.path.join(OUT, "pack_" + hid.replace(" ", "_") + ".glb")
    with open(out, "wb") as f:
        f.write(sc.export(file_type="glb", include_normals=True))
    return out, hsh.hexdigest()[:16], keys


def write_luau(packs):
    L = ["--!strict", "-- GENERATED by tools/meshgen/heroes/upload.py from data/hero_packs.json. Do not edit.",
         "-- [heroId] = Model asset id of the hero's packed pieces (one MeshPart per piece id).", "return {"]
    for k in sorted(packs):
        L.append(f"\t[{json.dumps(k)}] = {packs[k]['assetId']},")
    L.append("} :: { [string]: number }")
    with open(LUAU, "w") as f:
        f.write("\n".join(L) + "\n")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--only", default="")
    ap.add_argument("--dry", action="store_true")
    ap.add_argument("--force", action="store_true")
    ap.add_argument("--sync", action="store_true")
    a = ap.parse_args()
    packs = json.load(open(PACKS)) if os.path.exists(PACKS) else {}
    if a.sync:
        write_luau(packs)
        return
    import fcntl

    lock = open(os.path.join(OUT, ".upload.lock"), "w")
    try:
        fcntl.flock(lock, fcntl.LOCK_EX | fcntl.LOCK_NB)
    except OSError:
        sys.exit("another upload is running")
    build.load()
    man = json.load(open(os.path.join(OUT, "manifest.json")))
    hids = [h for h in sorted(kit.REG) if not a.only or h in a.only.split(",")]
    n = 0
    for hid in hids:
        H = build.get(hid)
        missing = [p["key"] for p in H.parts if p["kind"] == "piece" and not os.path.exists(os.path.join(OUT, p["key"] + ".glb"))]
        if missing:
            print(f"{hid}: {len(missing)} pieces not built, skipped")
            continue
        path, h, keys = pack(hid)
        prev = packs.get(hid)
        if prev and prev.get("hash") == h and not a.force:
            continue
        if a.dry:
            print("would upload", hid, len(keys), "pieces")
            continue
        tris = sum(man.get(k, {}).get("tris", 0) for k in keys)
        try:
            aid = base.upload(path, f"WE_hero_{hid}", f"WordEngine hero model '{hid}': {len(keys)} pieces, {tris} tris. Generated by tools/meshgen/heroes.")
        except Exception as e:
            print("FAILED", hid, e)
            continue
        packs[hid] = {"assetId": int(aid), "hash": h, "pieces": len(keys), "tris": tris}
        n += 1
        with open(LOG, "a") as f:
            f.write(f"{time.strftime('%Y-%m-%dT%H:%M:%SZ', time.gmtime())}\thero:{hid}\t{aid}\t{h}\t{tris}\n")
        print(f"{hid}: {aid} ({len(keys)} pieces, {tris} tris)")
        with open(PACKS, "w") as f:
            json.dump(dict(sorted(packs.items())), f, indent=1)
        write_luau(packs)
        time.sleep(0.3)
    with open(PACKS, "w") as f:
        json.dump(dict(sorted(packs.items())), f, indent=1)
    write_luau(packs)
    print(f"uploaded {n} packs")


if __name__ == "__main__":
    main()
