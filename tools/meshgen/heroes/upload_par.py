#!/usr/bin/env python3
"""Parallel variant of upload.py: packs + uploads every hero whose pack hash changed, N at a time.
  python3 tools/meshgen/heroes/upload_par.py [--jobs 4] [--only a,b]"""
import argparse, json, os, sys, time, threading
from concurrent.futures import ThreadPoolExecutor, as_completed

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import importlib.util
_spec = importlib.util.spec_from_file_location("hero_upload", os.path.join(HERE, "upload.py"))
U = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(U)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--jobs", type=int, default=4)
    ap.add_argument("--only", default="")
    a = ap.parse_args()
    packs = json.load(open(U.PACKS)) if os.path.exists(U.PACKS) else {}
    U.build.load()
    man = json.load(open(os.path.join(U.OUT, "manifest.json")))
    todo = []
    for hid in sorted(U.kit.REG):
        if a.only and hid not in a.only.split(","):
            continue
        H = U.build.get(hid)
        if any(p["kind"] == "piece" and not os.path.exists(os.path.join(U.OUT, p["key"] + ".glb")) for p in H.parts):
            print(hid, "pieces missing, skipped")
            continue
        path, h, keys = U.pack(hid)
        prev = packs.get(hid)
        if prev and prev.get("hash") == h:
            continue
        todo.append((hid, path, h, keys))
    print(len(todo), "to upload", flush=True)
    lock = threading.Lock()

    def one(t):
        hid, path, h, keys = t
        tris = sum(man.get(k, {}).get("tris", 0) for k in keys)
        for attempt in range(3):
            try:
                aid = U.base.upload(path, f"WE_hero_{hid}", f"WordEngine hero model '{hid}': {len(keys)} pieces, {tris} tris. Generated by tools/meshgen/heroes.")
                break
            except Exception as e:
                if attempt == 2:
                    return hid, None, str(e)
                time.sleep(5)
        with lock:
            packs[hid] = {"assetId": int(aid), "hash": h, "pieces": len(keys), "tris": tris}
            with open(U.LOG, "a") as f:
                f.write(f"{time.strftime('%Y-%m-%dT%H:%M:%SZ', time.gmtime())}\thero:{hid}\t{aid}\t{h}\t{tris}\n")
            with open(U.PACKS, "w") as f:
                json.dump(dict(sorted(packs.items())), f, indent=1)
            U.write_luau(packs)
        return hid, aid, None

    with ThreadPoolExecutor(a.jobs) as ex:
        for fut in as_completed([ex.submit(one, t) for t in todo]):
            hid, aid, err = fut.result()
            print(hid, aid or ("FAILED " + err), flush=True)
    print("done")


if __name__ == "__main__":
    main()
