#!/usr/bin/env python3
"""Upload generated .glb pieces to Roblox as Model assets (Open Cloud Assets API) and record them.

  python3 tools/meshgen/upload.py [--only id1,id2] [--force] [--dry]

* Reads tools/meshgen/out/manifest.json (written by build.py).
* Skips pieces whose glb hash matches the hash already recorded in data/mesh_assets.json (unless
  --force), so re-running only uploads changed sculpts. A piece whose hash matches ANOTHER recorded
  piece (for example one imported from Type-defend's manifest) reuses that asset id: nothing is ever
  uploaded twice.
* Uploads with creationContext.creator.groupId (the game's owning group), polls the operation with
  exponential backoff, appends every result to tools/meshgen/uploads.log and rewrites data/mesh_assets.json
  and the generated runtime module src/Shared/Meshes/MeshAssets.luau (no JSON decode at runtime).
* --sync only regenerates MeshAssets.luau from the JSON. --import <MeshAssets.json> merges another
  repository's manifest (records whose glb hash equals our build's hash; no upload).
* --adopt <MeshAssets.json> [more.json ...] takes another repository's records for every piece id both
  manifests list (asset id, size, origin, tris, hash; our set / flat are kept) so one id is one asset in both
  games. Adopted records carry "source": "adopted" and are never uploaded again from the local build, whose
  glb differs (only --force together with --only <id> replaces one).
* The egress proxy injects the API key; this script sends a placeholder header and never prints a key.
"""
import argparse, hashlib, json, os, subprocess, sys, time

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
OUT = os.path.join(HERE, "out")
ASSETS = os.path.join(ROOT, "data/mesh_assets.json")
LUAU = os.path.join(ROOT, "src/Shared/Meshes/MeshAssets.luau")
PREFIX = "WE_"
LOG = os.path.join(HERE, "uploads.log")
GROUP = "685727405"
API = "https://apis.roblox.com/assets/v1"


def sh(args):
    r = subprocess.run(args, capture_output=True, text=True)
    return r.returncode, r.stdout, r.stderr


def upload(path, name, desc):
    req = json.dumps({"assetType": "Model", "displayName": name, "description": desc, "creationContext": {"creator": {"groupId": GROUP}}})
    delay = 2.0
    for attempt in range(8):
        code, out, err = sh(["curl", "-sS", "-X", "POST", API + "/assets", "-H", "x-api-key: dummy", "-w", "\n%{http_code}",
                             "-F", f"request={req};type=application/json", "-F", f"fileContent=@{path};type=model/gltf-binary"])
        body, _, status = out.rpartition("\n")
        if status == "200":
            op = json.loads(body)
            return poll(op.get("operationId") or op["path"].split("/")[-1])
        if status in ("429", "500", "502", "503", "504") or code != 0:
            time.sleep(delay)
            delay = min(delay * 2, 60)
            continue
        raise RuntimeError(f"upload {name}: HTTP {status} {body[:300]}")
    raise RuntimeError(f"upload {name}: gave up after retries")


def poll(op_id):
    delay = 1.0
    for _ in range(40):
        code, out, err = sh(["curl", "-sS", API + "/operations/" + op_id, "-H", "x-api-key: dummy", "-w", "\n%{http_code}"])
        body, _, status = out.rpartition("\n")
        if status == "200":
            j = json.loads(body)
            if j.get("done"):
                if "response" in j and j["response"].get("assetId"):
                    return j["response"]["assetId"]
                raise RuntimeError(f"operation {op_id} failed: {json.dumps(j)[:300]}")
        elif status not in ("429", "500", "502", "503", "504"):
            raise RuntimeError(f"poll {op_id}: HTTP {status} {body[:300]}")
        time.sleep(delay)
        delay = min(delay * 1.6, 15)
    raise RuntimeError(f"operation {op_id} timed out")


def _num(v):
    return repr(int(v)) if float(v) == int(v) else repr(round(float(v), 4))


def write_luau(assets):
    """Generated runtime manifest: a plain Luau table, one piece per line."""
    out = ["--!strict", "-- GENERATED by tools/meshgen/upload.py from data/mesh_assets.json. Do not edit.",
           "-- [pieceId] = { assetId, size (native, studs or unit-box units), origin, tris, kind (box|anchor|unit), set, flat }", "return {"]
    for k, v in sorted(assets.items()):
        flat = "{ " + ", ".join(json.dumps(x) for x in v.get("flat", [])) + " }" if v.get("flat") else "{}"
        out.append('\t[%s] = { assetId = %d, size = { %s }, origin = { %s }, tris = %d, kind = %s, set = %s, flat = %s },' % (
            json.dumps(k), v["assetId"], ", ".join(_num(x) for x in v["size"]), ", ".join(_num(x) for x in v["origin"]),
            v["tris"], json.dumps(v.get("kind", "box")), json.dumps(v.get("set", "td")), flat))
    out.append("} :: { [string]: { assetId: number, size: { number }, origin: { number }, tris: number, kind: string, set: string, flat: { string } } }")
    os.makedirs(os.path.dirname(LUAU), exist_ok=True)
    with open(LUAU, "w") as f:
        f.write("\n".join(out) + "\n")


def write_assets(assets):
    """One piece per line (diff-friendly); also regenerates the Luau module."""
    lines = [f"  {json.dumps(k)}: {json.dumps(v, separators=(', ', ': '))}" for k, v in sorted(assets.items())]
    with open(ASSETS, "w") as f:
        f.write("{\n" + ",\n".join(lines) + "\n}\n")
    write_luau(assets)


def glb_hash(pid):
    return hashlib.sha1(open(os.path.join(OUT, pid + ".glb"), "rb").read()).hexdigest()[:16]


def record(info, aid, h):
    rec = {k: info[k] for k in ("size", "origin", "tris", "kind", "pivot")}
    rec["assetId"] = int(aid)
    rec["hash"] = h
    rec["set"] = info.get("set", "td")
    rec["flat"] = info.get("flat", [])
    return rec


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--only", default="")
    ap.add_argument("--force", action="store_true")
    ap.add_argument("--dry", action="store_true")
    ap.add_argument("--max", type=int, default=400)
    ap.add_argument("--sync", action="store_true")
    ap.add_argument("--import", dest="imp", default="")
    ap.add_argument("--adopt", nargs="+", default=[])
    a = ap.parse_args()
    man = json.load(open(os.path.join(OUT, "manifest.json")))
    assets = json.load(open(ASSETS)) if os.path.exists(ASSETS) else {}
    if a.sync:
        write_assets(assets)
        print(f"synced {len(assets)} records")
        return
    if a.adopt:
        took = same = 0
        for path in a.adopt:
            for pid, rec in sorted(json.load(open(path)).items()):
                mine = assets.get(pid)
                if mine is None or not rec.get("assetId"):
                    continue
                if mine.get("assetId") == rec["assetId"]:
                    same += 1
                    continue
                for k in ("size", "origin", "tris", "kind", "pivot", "assetId", "hash"):
                    if k in rec:
                        mine[k] = rec[k]
                mine["source"] = "adopted"
                took += 1
        write_assets(assets)
        print(f"adopted {took} records ({same} already identical)")
        return
    if a.imp:
        other = json.load(open(a.imp))
        took = 0
        for pid, rec in sorted(other.items()):
            if pid in man and os.path.exists(os.path.join(OUT, pid + ".glb")) and glb_hash(pid) == rec.get("hash"):
                assets[pid] = record(man[pid], rec["assetId"], rec["hash"])
                took += 1
        write_assets(assets)
        print(f"imported {took}/{len(other)} records with identical hashes")
        return
    # one uploader at a time: two concurrent runs each upload every pending piece (22 duplicate assets were made
    # that way once, see uploads_orphans.tsv)
    import fcntl
    lock = open(os.path.join(OUT, ".upload.lock"), "w")
    try:
        fcntl.flock(lock, fcntl.LOCK_EX | fcntl.LOCK_NB)
    except OSError:
        sys.exit("another upload.py is running; wait for it to finish")
    assets = json.load(open(ASSETS)) if os.path.exists(ASSETS) else {}
    only = {s for s in a.only.split(",") if s}
    by_hash = {v["hash"]: v["assetId"] for v in assets.values() if v.get("hash")}
    n = 0
    for pid in sorted(man):
        if only and pid not in only:
            continue
        info = man[pid]
        path = os.path.join(OUT, pid + ".glb")
        h = glb_hash(pid)
        prev = assets.get(pid)
        if prev and prev.get("source") == "adopted" and not (a.force and pid in only):
            continue  # this id is another repository's asset: the local build never replaces it
        if prev and prev.get("hash") == h and not a.force:
            if prev.get("flat") != info.get("flat", []) or prev.get("set") != info.get("set", "td"):
                assets[pid] = record(info, prev["assetId"], h)
            continue
        if h in by_hash and not a.force:  # identical mesh already uploaded under another id
            assets[pid] = record(info, by_hash[h], h)
            print(f"{pid}: reuses asset {by_hash[h]} (same hash)")
            continue
        if n >= a.max:
            print("upload cap reached")
            break
        if a.dry:
            print("would upload", pid)
            n += 1
            continue
        try:
            aid = upload(path, f"{PREFIX}{pid}", f"WordEngine mesh piece '{pid}' ({info['tris']} tris). Generated by tools/meshgen.")
        except Exception as e:  # keep going; report at the end
            print("FAILED", pid, e)
            continue
        n += 1
        assets[pid] = record(info, aid, h)
        by_hash[h] = int(aid)
        with open(LOG, "a") as f:
            f.write(f"{time.strftime('%Y-%m-%dT%H:%M:%SZ', time.gmtime())}\t{pid}\t{aid}\t{h}\t{info['tris']}\n")
        print(f"{pid}: {aid}")
        write_assets(assets)
        time.sleep(0.3)
    write_assets(assets)
    print(f"uploaded {n}")


if __name__ == "__main__":
    main()
